#!/usr/bin/env python3
"""generate-theme.py — compile design/tokens.json into shell/triton/Theme.qml.

The design tokens are the single source of truth for every visual decision in
the Triton shell. Hand-editing Theme.qml is forbidden: it is regenerated by
this script, and the generated file carries a warning header. If a token is
missing, this script fails loudly rather than inventing a value.

Usage:
    scripts/generate-theme.py [--check]

    --check   verify the committed Theme.qml is in sync with tokens.json
              (used by lint/CI); exits non-zero if regeneration would differ.
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TOKENS_PATH = REPO_ROOT / "design" / "tokens.json"
THEME_PATH = REPO_ROOT / "shell" / "triton" / "Theme.qml"
CODEPOINTS_PATH = REPO_ROOT / "design" / "fonts" / "symbols.codepoints"
ICONS_PATH = REPO_ROOT / "shell" / "triton" / "Icons.qml"

HEADER = """// GENERATED FILE — DO NOT EDIT.
// Produced by scripts/generate-theme.py from design/tokens.json.
// Regenerate: scripts/generate-theme.py
"""


def fail(msg: str) -> "SystemExit":
    return SystemExit(f"generate-theme: error: {msg}")


def require(obj: dict, key: str, ctx: str):
    if key not in obj:
        raise fail(f"missing required token '{key}' in {ctx}")
    return obj[key]


def qml_color(hexval: str, alpha: float = 1.0) -> str:
    """Convert '#RRGGBB' + alpha to QML-compatible '#AARRGGBB' or '#RRGGBB'."""
    hexval = hexval.lstrip("#")
    if alpha >= 1.0:
        return f"#{hexval.upper()}"
    a = round(alpha * 255)
    return f"#{a:02X}{hexval.upper()}"


def strip_commentish(value):
    """Tokens sometimes carry units or notes ('#2458C8 (approximate)')."""
    if isinstance(value, str):
        return value.split(" ")[0]
    return value


UI_DIR = REPO_ROOT / "shell" / "triton" / "tokens"


def camel(name: str) -> str:
    """Material role name -> QML property (on_primary -> onprimary)."""
    prop = re.sub(r"_([a-z])", lambda m: m.group(1).upper(), name)
    return prop.lower() if re.match(r"on[A-Z]", prop) else prop


def singleton(imports: list, body: list) -> str:
    return "\n".join([HEADER, "pragma Singleton", *imports, "", "QtObject {", *body, "}", ""])


def ui_tokens(tokens: dict) -> dict:
    """Render the component-shell token singletons. Returns {path: text}."""
    ui = require(tokens, "ui", "root")
    shape = tokens["shape"]["wave"]
    density = '    readonly property bool board: Quickshell.env("CALLISTO_DENSITY") === "board"'

    metrics = [density, ""]
    for name, (compact, board) in ui["metrics"].items():
        value = compact if compact == board else f"board ? {board} : {compact}"
        metrics.append(f"    readonly property real {name}: {value}")
    metrics += ["", f'    readonly property string wavePath: "{shape["path"]}"']

    families = tokens["type"]["families"]
    roles = []
    for name, spec in ui["type"].items():
        if name.startswith("_"):
            continue
        family, weight, size, line = spec
        roles.append(
            f'        "{name}": {{ family: "{families[family]}", weight: {weight}, '
            f"size: board ? {size[1]} : {size[0]}, line: board ? {line[1]} : {line[0]} }},"
        )
    typography = [density, "", "    readonly property var roles: ({", *roles, "    })"]

    motion = ['    // Springs are [stiffness, damping ratio].']
    for name in ("spatial_fast", "spatial_default", "spatial_slow"):
        k, z = tokens["motion"][name]
        motion.append(f"    readonly property var {camel(name)}: [{k}, {z}]")
    motion.append("")
    motion.append("    property bool reduce: Theme.reduceMotion")
    fade = ui["fade"]
    for name in ("fast", "default", "slow"):
        key = "fade" + name.capitalize()
        motion.append(f'    readonly property int {key}: reduce ? {fade["reduced"]} : {fade[name]}')
    motion.append("")
    for name, val in ui["timing"].items():
        motion.append(f"    readonly property int {name}: {val}")

    colors = []
    for mode in ("dark", "light"):
        colors.append(f"    readonly property Scheme {mode}: Scheme {{")
        for name, val in tokens["color"][mode].items():
            v = strip_commentish(val)
            if re.fullmatch(r"#[0-9A-Fa-f]{6}", v):
                colors.append(f'        {camel(name)}: "{v.upper()}"')
        for name, val in ui["material"][mode].items():
            key = name if name == "ink" else name + "Alpha"
            colors.append(f'        {key}: "{val}"' if name == "ink" else f"        {key}: {val}")
        colors.append("    }")
    colors += [
        "",
        '    readonly property Scheme current: Theme.activeMode === "light" ? light : dark',
        "",
        "    // The engine writes the user's palette to tokens.json; Theme parses it.",
        "    function load() {",
        "        const user = Theme.userTokens?.color;",
        "        if (!user)",
        "            return;",
        "        dark.assign(user.dark);",
        "        light.assign(user.light);",
        "    }",
        "",
        "    property Connections follow: Connections {",
        "        target: Theme",
        "        function onUserTokensChanged() { root.load(); }",
        "    }",
        "    Component.onCompleted: load()",
    ]
    colors = ["    id: root", "", *colors]

    scheme_names = [camel(n) for n, v in tokens["color"]["dark"].items()
                    if re.fullmatch(r"#[0-9A-Fa-f]{6}", strip_commentish(v))]
    scheme = [HEADER, "import QtQuick", "",
              "// One color scheme: the Material roles plus the materials derived from them.",
              "QtObject {"]
    scheme += [f"    property color {n}" for n in scheme_names]
    scheme += [
        "",
        "    property color ink",
        "    property real micaAlpha",
        "    property real glassAlpha",
        "    property real thickAlpha",
        "    property real veilAlpha",
        "    property real veilHiAlpha",
        "    property real highlightAlpha",
        "    property real hairlineAlpha",
        "",
        "    readonly property color mica: Qt.alpha(surfaceContainerLow, micaAlpha)",
        "    readonly property color glass: Qt.alpha(surfaceContainerHigh, glassAlpha)",
        "    readonly property color thick: Qt.alpha(surfaceContainerHigh, thickAlpha)",
        "    readonly property color veil: Qt.alpha(ink, veilAlpha)",
        "    readonly property color veilHi: Qt.alpha(ink, veilHiAlpha)",
        '    readonly property color highlight: Qt.rgba(1, 1, 1, highlightAlpha)',
        "    readonly property color hairline: Qt.alpha(ink, hairlineAlpha)",
        "    // Dims the screen behind a modal surface.",
        "    readonly property color scrim: Qt.rgba(0, 0, 0, 0.3)",
        "",
        "    function assign(roles) {",
        "        for (const key in roles) {",
        "            let prop = key.replace(/_([a-z])/g, (m, c) => c.toUpperCase());",
        "            if (/^on[A-Z]/.test(prop))",
        "                prop = prop.toLowerCase();",
        "            if (prop in this)",
        "                this[prop] = roles[key];",
        "        }",
        "    }",
        "}",
        "",
    ]

    return {
        UI_DIR / "Metrics.qml": singleton(["import Quickshell", "import QtQuick"], metrics),
        UI_DIR / "Typography.qml": singleton(["import Quickshell", "import QtQuick"], typography),
        UI_DIR / "Motion.qml": singleton(["import QtQuick", "import qs"], motion),
        UI_DIR / "Colors.qml": singleton(["import QtQuick", "import qs"], colors),
        UI_DIR / "Scheme.qml": "\n".join(scheme),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    tokens = json.loads(TOKENS_PATH.read_text())
    dark = require(tokens["color"], "dark", "color")
    material = require(tokens, "material", "root")
    shape = require(tokens, "shape", "root")
    space = require(tokens, "space", "root")
    typeface = require(tokens["type"], "families", "type")
    motion = require(tokens, "motion", "root")
    state_layer = require(tokens, "state_layer", "root")
    size = tokens.get("size", {})

    wave = require(shape, "wave", "shape")
    wave_path = require(wave, "path", "shape.wave")

    glass = require(material, "glass", "material")
    mica = require(material, "mica", "material")
    thick = material.get("thick_glass", material.get("thickglass"))
    if thick is None:
        raise fail("missing required token 'thick_glass' in material")

    def color(name: str) -> str:
        return strip_commentish(require(dark, name, "color.dark"))

    lines = [
        HEADER,
        "pragma Singleton",
        "import QtQuick",
        "",
        "QtObject {",
        "    id: root",
        "",
        "    // ---- Identity ----",
        f'    readonly property string tokenVersion: "{tokens["version"]}"',
        "",
        "    // ---- Color: dark scheme (verbatim from tokens.json) ----",
    ]

    for name, val in dark.items():
        v = strip_commentish(val)
        if not re.fullmatch(r"#[0-9A-Fa-f]{6}", v):
            continue  # skip non-color metadata
        # QML reserves identifiers of the form onX for signal handlers, so the
        # Material "on_*" tokens cannot use camelCase (onPrimary would parse
        # as a handler). The canonical spellings are onprimary, onsurface, ...
        # — lowercase, close to the tokens, and unambiguous in QML.
        prop = re.sub(r"_([a-z])", lambda m: m.group(1).upper(), name)
        if re.match(r"on[A-Z]", prop):
            prop = prop.lower()
        # Mutable, not readonly: the settings app's theme engine writes
        # ~/.config/callisto/tokens.json and the shell re-applies it live via
        # applyUserTokens() below. Reassigning these by hand is still
        # forbidden — the engine is the only writer.
        lines.append(f'    property color {prop}: "{v.upper()}"')
        if prop != name and not re.match(r"on[A-Z]", re.sub(r"_([a-z])", lambda m: m.group(1).upper(), name)):
            lines.append(f'    property color {name}: "{v.upper()}"')

    lines += [
        "",
        "    // ---- Materials (fill color pre-composited with alpha) ----",
        f'    property color glassBg: "{qml_color(color("surface_container_high"), float(glass["alpha"]))}"',
        f'    readonly property real glassBlur: {glass["blur"]}',
        f'    readonly property color micaBg: "{qml_color(color("surface_container_low"), float(mica["alpha"]))}"',
        f'    readonly property real micaBlur: {mica["blur"]}',
        f'    readonly property color thickGlassBg: "{qml_color(color("surface_container_high"), float(thick["alpha"]))}"',
        f'    readonly property real thickGlassBlur: {thick.get("blur", 0)}',
    ]

    lines.append(f'    readonly property color veil: "{qml_color("FFFFFF", float(tokens["ui"]["material"]["dark"]["veil"]))}"')
    lines.append(f'    readonly property color veilBright: "{qml_color("FFFFFF", float(tokens["ui"]["material"]["dark"]["veilHi"]))}"')

    lines += [
        "",
        "    // ---- State layers ----",
    ]
    for name, val in state_layer.items():
        lines.append(f'    readonly property real state{name.capitalize().replace("_", "")}: {val}')

    lines += [
        "",
        "    // ---- Shape (logical px) ----",
    ]
    for key in ("tiled", "xs", "sm", "md", "lg", "xl", "full"):
        if key in shape:
            lines.append(f'    readonly property real radius{key.capitalize()}: {shape[key]}')
    lines.append(f'    readonly property real radiusFloating: {shape.get("floating_window", shape.get("xl", 28))}')

    lines += [
        "",
        "    // ---- Spacing scale (index into the scale) ----",
        "    readonly property var space: [" + ", ".join(str(s) for s in space) + "]",
        "",
        "    // ---- Typography ----",
        f'    readonly property string fontDisplay: "{typeface["display"]}"',
        f'    readonly property string fontUi: "{typeface["ui"]}"',
        f'    readonly property string fontUiFallback: "Inter"',
        f'    readonly property string fontMono: "{typeface["mono"]}"',
        f'    readonly property string fontIcons: "{typeface["icons"]}"',
        "",
        "    // ---- Motion: [stiffness, damping_ratio] spring pairs ----",
    ]
    for name in ("spatial_fast", "spatial_default", "spatial_slow", "effects_fast", "effects_default", "effects_slow"):
        if name in motion:
            s, d = motion[name]
            prop = re.sub(r"_([a-z])", lambda m: m.group(1).upper(), name)
            lines.append(f"    readonly property var motion{prop[0].upper() + prop[1:]}: [{s}, {d}]")

    lines += [
        "",
        "    // ---- Veil alphas + semantic accents: the white-on-glass overlays",
        "    // and status colors the boards use as bare literals. Centralizing",
        "    // them means light mode can restate them if needed.",
        '    readonly property color veilLow: "#17FFFFFF"',
        '    readonly property color veilMid: "#1FFFFFFF"',
        '    readonly property color veilHigh: "#4DFFFFFF"',
        '    readonly property color successtint: "#8CD6A0"',
        '    readonly property color onsuccess: "#00391B"',
        "",
        "    // ---- Sizes ----",
        f'    readonly property real barHeight: {size.get("bar_height", 56)}',
        "",
        "    // ---- Identity: the Triton wave ----",
        f'    readonly property string waveViewBox: "{wave["viewBox"]}"',
        f'    readonly property int waveLobes: {wave["lobes"]}',
        f'    readonly property string wavePath: "{wave_path}"',
        "",
        "    // ---- Live re-application (the no-dotfiles contract) ----",
        "    // The theme engine (callisto-apply) writes user-resolved tokens to",
        "    // ~/.config/callisto/tokens.json; shell.qml watches that file and",
        "    // calls this with its parsed content. Property naming mirrors the",
        "    // snake_case -> camelCase rules above, including the on* lowering.",
        "    // The parsed tokens file, retained so auto mode can re-resolve without",
        "    // a reload — the file doesn't change at dawn/dusk, the resolution does.",
        "    property var userTokens: null",
        "    property string activeMode: \"dark\"",
        "",
        "    // Reduce motion: store-driven, shell-wide. Consumers scale their",
        "    // durations to zero when this is on — accessibility requirement, and",
        "    // it doubles as a low-power mode on weak compositors.",
        "    property bool reduceMotion: false",
        "",
        "    // Auto mode resolution: day window 07:00–19:00 local. Without location",
        "    // data this is a fixed approximation of sunrise/sunset — honest and",
        "    // correct within an hour for most users.",
        "    function resolveMode(mode) {",
        "        if (mode !== \"auto\")",
        "            return mode;",
        "        const h = new Date().getHours();",
        "        return (h >= 7 && h < 19) ? \"light\" : \"dark\";",
        "    }",
        "",
        "    function applyUserTokens(parsed) {",
        "        if (!parsed || !parsed.color)",
        "            return;",
        "        userTokens = parsed;",
        "        const mode = parsed.active_mode || \"dark\";",
        "        activeMode = resolveMode(mode);",
        "        const scheme = (activeMode === \"light\" && parsed.color.light)",
        "            ? parsed.color.light : parsed.color.dark;",
        "        if (!scheme)",
        "            return;",
        "        for (const key of Object.keys(scheme)) {",
        "            const value = scheme[key];",
        "            if (typeof value !== \"string\" || !/^#[0-9A-Fa-f]{6}([0-9A-Fa-f]{2})?$/.test(value))",
        "                continue;",
        '            let prop = key.replace(/_([a-z])/g, (m, c) => c.toUpperCase());',
        '            if (/^on[A-Z]/.test(prop))',
        '                prop = prop.toLowerCase();',
        "            if (prop in this)",
        '                this[prop] = value.toUpperCase();',
        "            if (key in this && key !== prop)",
        '                this[key] = value.toUpperCase();',
        "        }",
        "        // Derived glass fill follows the scheme — it's an alpha-composited",
        "        // surface_container_high, so light/dark must restate it.",
        "        if (scheme.surface_container_high)",
        '            glassBg = "#B2" + scheme.surface_container_high.substring(1).toUpperCase();',
        "    }",
        "}",
        "",
    ]

    output = "\n".join(lines)

    # ---- Icons singleton ------------------------------------------------------
    # Material Symbols ligatures ("wifi" as literal text) depend on OpenType
    # liga/dlig shaping, which Qt does not reliably enable. Direct codepoints
    # always render — same as the Rust implementation. Generated from
    # design/fonts/symbols.codepoints, the subset manifest for TritonSymbols.
    if CODEPOINTS_PATH.exists():
        icon_lines = [
            HEADER,
            "pragma Singleton",
            "import QtQuick",
            "",
            "// Icon codepoints in the Triton Symbols font. Use as:",
            "//   text: Icons.wifi   font.family: \"Triton Symbols\"",
            "QtObject {",
        ]
        # JavaScript reserved words cannot be property identifiers in QML
        # object literals — one illegal name (e.g. "delete") invalidates the
        # entire singleton type, not just that property.
        RESERVED = {
            "break", "case", "catch", "class", "const", "continue", "debugger",
            "default", "delete", "do", "else", "enum", "export", "extends",
            "false", "finally", "for", "function", "if", "import", "in",
            "instanceof", "new", "null", "return", "super", "switch", "this",
            "throw", "true", "try", "typeof", "var", "void", "while", "with",
            "yield", "let", "static", "await",
            # strict-mode future reserved words — QML rejects them too
            "implements", "interface", "package", "private", "protected",
            "public",
        }
        count = 0
        for line in CODEPOINTS_PATH.read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) != 2:
                continue
            name, cp = parts
            # snake_case -> camelCase. Underscores before digits disappear
            # entirely (battery_5_bar -> battery5Bar), letters capitalize.
            prop = re.sub(r"_([a-z0-9])", lambda m: m.group(1).upper() if m.group(1).isalpha() else m.group(1), name)
            if prop[0].isdigit():
                prop = "icon" + prop
            if prop in RESERVED:
                prop = prop + "Icon"
            icon_lines.append(f'    readonly property string {prop}: "\\u{cp}"')
            count += 1
        icon_lines += ["}", ""]
        outputs = {ICONS_PATH: "\n".join(icon_lines)}
    else:
        outputs = {}

    outputs[THEME_PATH] = output
    outputs.update(ui_tokens(tokens))

    if args.check:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        for path in stale:
            print(f"generate-theme: {path.relative_to(REPO_ROOT)} is out of sync", file=sys.stderr)
        if not stale:
            print("generate-theme: generated files are in sync")
        return 1 if stale else 0

    UI_DIR.mkdir(exist_ok=True)
    for path, text in outputs.items():
        path.write_text(text)
        print(f"generate-theme: wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
