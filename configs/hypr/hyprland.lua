-- Callisto Hyprland configuration — Lua (hyprland 0.55+ era).
--
-- Triton layout principles:
--   1. Tiled windows: zero gaps, zero rounding. Radius and blur belong only
--      to floating surfaces and shell panels.
--   2. Glass materials get their blur from the compositor here — the shell
--      itself only ships translucent fills.
--   3. Nothing here is user-serviceable: the Settings app owns every knob a
--      user should ever turn, writing through the settings store. If you find
--      yourself editing this file by hand, that's a missing settings panel.
--
-- User overrides are generated by the settings engine into
-- ~/.config/hypr/callisto-user.lua and required below (protected, so a bad
-- generated file can never break the session).

