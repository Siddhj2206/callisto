-- --- Floating surfaces get the Triton radius ------------------------------------
hl.window_rule({ match = { float = true }, rounding = 20 })

-- Shell dialogs and settings windows float by design.
hl.window_rule({ match = { class = "^(org\\.callisto\\.Settings)$" }, float = true, center = true, rounding = 20, xray = true })

-- --- Layer rules: shell materials -------------------------------------------------
-- Quickshell layer surfaces get compositor blur for Glass and Thick Glass.
-- ignore_alpha keeps fully-transparent regions (everything outside the
-- bar islands) from catching the effect.
-- "triton-glass" is the bar, quick settings, center, toasts and OSD: their
-- blur samples the wallpaper only (xray). The rest of the shell's layers
-- (launcher, clipboard, switcher, dialogs) blur the windows below.
--
-- Hyprland cuts the blur out with a hard edge, so it must start only where a
-- panel is nearly all there, or rounded corners get a jagged fringe. Keep each
-- value under the lowest fill it has to blur: glass and mica are .70 and up,
-- the power menu's backdrop (a "quickshell" layer) is .60.
hl.layer_rule({ match = { namespace = "^(quickshell)$" }, blur = true, ignore_alpha = 0.55, no_anim = true })
hl.layer_rule({ match = { namespace = "^(triton-glass)$" }, blur = true, ignore_alpha = 0.65, no_anim = true, xray = true })

-- --- Session autostart --------------------------------------------------------------
-- The shell IS the wallpaper renderer (Desktop.qml layer surface) — no swaybg
-- or hyprpaper. It runs as callisto-shell.service, which restarts it if it dies,
-- and the polkit agent is a unit too (hyprpolkitagent, enabled globally).
-- Everything user-facing spawns through `uwsm app --` so apps land in proper
-- systemd scopes instead of inside the compositor unit.
hl.on("hyprland.start", function()
    -- Only for start-callisto's last resort, a session without uwsm.
    hl.exec_cmd("command -v uwsm >/dev/null || qs -n -c triton")
end)

-- --- Keybinds ----------------------------------------------------------------------------
-- Shell surfaces are driven through quickshell IPC — the shell is the single
-- source of truth for its own visibility. Nothing here shells out to ad-hoc
-- UI binaries; if a surface exists, it answers IPC.

local function qsipc(target, fn)
    return hl.dsp.exec_cmd("uwsm app -- qs -c triton ipc call " .. target .. " " .. fn)
end

